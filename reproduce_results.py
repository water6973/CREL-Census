#!/usr/bin/env python3
"""Regenerate LaTeX results tables from results_table_prf.csv."""

from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent
CSV = ROOT / "results_table_prf.csv"
OUT = ROOT / "results_tables.tex"

FEATURE_LABELS = {
    "static_only": "Static only",
    "quarterly_only": "Quarterly county/QWI",
    "quarterly_lagged": "Quarterly + eight-quarter lags",
    "full": "Full specification",
}

TARGETS = (
    ("panel_period", "panel", "Panel-period closure"),
    ("next_quarter", "next_q", "Next-quarter closure"),
)

ALGOS = ("xgboost", "ngboost", "catboost")


def fmt(x: float) -> str:
    return f"{x:.3f}"


def write_tables(df: pd.DataFrame, path: Path) -> None:
    lines: list[str] = []
    lines.append(r"% Auto-generated by reproduce_results.py")
    lines.append("")

    for _target_dir, prefix, title in TARGETS:
        label = "panel" if prefix == "panel" else "nextq"
        lines.append(r"\begin{table}[htbp]")
        lines.append(r"\centering")
        lines.append(r"\begin{threeparttable}")
        lines.append(
            rf"\caption{{{title}: test precision and recall at the validation-tuned "
            rf"threshold that maximizes $F_1$ (raw scores)}}"
        )
        lines.append(rf"\label{{tab:results_f1_{label}}}")
        lines.append(r"\footnotesize")
        lines.append(r"\setlength{\tabcolsep}{5pt}")
        lines.append(r"\begin{tabular}{@{}l *{9}{c}@{}}")
        lines.append(r"\toprule")
        lines.append(
            r" & \multicolumn{3}{c}{XGBoost} & \multicolumn{3}{c}{NGBoost} "
            r"& \multicolumn{3}{c}{CatBoost} \\"
        )
        lines.append(r"\cmidrule(lr){2-4} \cmidrule(lr){5-7} \cmidrule(lr){8-10}")
        lines.append(
            r"Feature specification & $P$ & $R$ & $F_1$ & $P$ & $R$ & $F_1$ "
            r"& $P$ & $R$ & $F_1$ \\"
        )
        lines.append(r"\midrule")
        for _, row in df.iterrows():
            fs = row["feature_set"]
            feat = FEATURE_LABELS[fs]
            vals = []
            for algo in ALGOS:
                vals.extend(
                    [
                        row[f"{prefix}_{algo}_prec"],
                        row[f"{prefix}_{algo}_rec"],
                        row[f"{prefix}_{algo}_f1"],
                    ]
                )
            cells = " & ".join(fmt(v) for v in vals)
            lines.append(f"{feat} & {cells} \\\\")
        lines.append(r"\bottomrule")
        lines.append(r"\end{tabular}")
        lines.append(r"\begin{tablenotes}[flushleft]")
        lines.append(r"\footnotesize")
        lines.append(r"\medskip")
        if prefix == "panel":
            note = (
                r"\item Outcome is whether \texttt{CLOSED\_ON} is recorded during the "
                r"study window (2019Q3--2025Q2). For each algorithm, the threshold "
                r"maximizing validation $F_1$ is applied to raw test scores."
            )
        else:
            note = (
                r"\item Outcome is \texttt{CLOSED\_NEXT\_QUARTER}. Temporal holdout on "
                r"calendar quarters. Threshold tuned on validation $F_1$."
            )
        lines.append(note)
        lines.append(r"\end{tablenotes}")
        lines.append(r"\end{threeparttable}")
        lines.append(r"\end{table}")
        lines.append("")

    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    if not CSV.exists():
        raise SystemExit(f"Missing {CSV}")
    write_tables(pd.read_csv(CSV), OUT)
    print(f"Wrote {OUT}")
    print(f"Figure: {ROOT / 'figures' / 'pr_overlay_6panel.pdf'}")


if __name__ == "__main__":
    main()
